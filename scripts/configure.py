#!/usr/bin/env python3
"""Resolve Kconfig once for both CMake and C++; never parse .config by hand."""
import argparse
import os
from pathlib import Path
import sys

try:
    import kconfiglib
except ImportError:
    sys.exit("Kconfiglib is required. Install requirements.txt in .venv, or select a Python with Kconfiglib using -DPython3_EXECUTABLE=...")


def write_changed(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    if not path.exists() or path.read_text() != text:
        path.write_text(text)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, required=True)
    parser.add_argument("--build", type=Path, required=True)
    parser.add_argument("--defconfig", type=Path, required=True)
    parser.add_argument("--menuconfig", action="store_true")
    parser.add_argument("--savedefconfig", action="store_true")
    args = parser.parse_args()
    source, build = args.source.resolve(), args.build.resolve()
    build.mkdir(parents=True, exist_ok=True)
    config = build / ".config"
    os.environ["srctree"] = str(source)
    os.environ["KCONFIG_CONFIG"] = str(config)
    kconf = kconfiglib.Kconfig(str(source / "Kconfig"), warn_to_stderr=False)
    kconf.warn_assign_undef = True
    kconf.load_config(str(config if config.exists() else args.defconfig.resolve()))
    # Force evaluation before checking warnings (e.g. invalid numeric ranges).
    for symbol in kconf.unique_defined_syms:
        _ = symbol.str_value
    if kconf.warnings:
        sys.exit("Invalid Kconfig configuration:\n" + "\n".join(kconf.warnings))
    if not kconf.syms["BOARD_NUCLEO_F411RE"].tri_value:
        sys.exit("No supported board selected")
    kconf.write_config(str(config))
    if args.menuconfig:
        from menuconfig import menuconfig
        menuconfig(kconf)
        # CMake regenerates on the next build using the saved .config.
        return
    if args.savedefconfig:
        path = build / "defconfig"
        kconf.write_min_config(str(path))
        print(f"Saved minimal configuration to {path}")
        return

    enabled = bool(kconf.syms["ARTOS"].tri_value)
    # Disabled subsystem settings have no Kconfig value. Provide safe inert
    # defaults so public type declarations remain usable by compile-only checks.
    tick = int(kconf.syms["ARTOS_TICK_HZ"].str_value) if enabled else 1000
    priorities = int(kconf.syms["ARTOS_PRIORITY_LEVELS"].str_value) if enabled else 16
    monitor_enabled = bool(kconf.syms["MONITOR"].tri_value)
    rx_size = int(kconf.syms["MONITOR_RX_BUFFER_SIZE"].str_value) if monitor_enabled else 0
    workspace_size = int(kconf.syms["MONITOR_WORKSPACE_SIZE"].str_value) if monitor_enabled else 0
    generated = build / "generated"
    generated.mkdir(exist_ok=True)
    kconf.write_autoconf(str(generated / "autoconf.h"))
    write_changed(generated / "build_config.h", f'''// Generated by scripts/configure.py. Edit .config through menuconfig.
#pragma once
#include <cstddef>
#include <cstdint>
#include <autoconf.h>

namespace build_config {{
    namespace artos {{
        inline constexpr bool enabled = {str(enabled).lower()};
        inline constexpr std::uint32_t tick_hz = {tick};
        inline constexpr std::uint32_t priority_levels = {priorities};
        static_assert(tick_hz > 0);
        static_assert(priority_levels > 0 && priority_levels <= 256);
    }}
    namespace monitor {{
        inline constexpr bool enabled = {str(monitor_enabled).lower()};
        inline constexpr std::size_t workspace_size = {workspace_size};
        inline constexpr std::size_t rx_buffer_size = {rx_size};
        static_assert(!enabled || (rx_buffer_size > 1 && rx_buffer_size <= UINT32_MAX));
    }}
}}
''')
    write_changed(generated / "config.cmake", f'''# Generated by scripts/configure.py.
set(CONFIG_BSP "nucleo_f411re")
set(CONFIG_ARTOS {"ON" if enabled else "OFF"})
set(CONFIG_MONITOR {"ON" if monitor_enabled else "OFF"})
set(CONFIG_MONITOR_WORKSPACE_SIZE {workspace_size})
''')


if __name__ == "__main__":
    main()
