#!/usr/bin/env python3
"""Resolve Kconfig once for both CMake and C++; never parse .config by hand."""
import argparse
import os
from pathlib import Path
import sys

try:
    import kconfiglib
except ImportError:
    sys.exit("Kconfiglib is required. Install requirements.txt in .venv, or select a Python with Kconfiglib using -DPython3_EXECUTABLE=...")


def write_changed(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    if not path.exists() or path.read_text() != text:
        path.write_text(text)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, required=True)
    parser.add_argument("--build", type=Path, required=True)
    parser.add_argument("--defconfig", type=Path, required=True)
    parser.add_argument("--build-type", default="Release")
    parser.add_argument("--menuconfig", action="store_true")
    parser.add_argument("--savedefconfig", action="store_true")
    args = parser.parse_args()
    source, build = args.source.resolve(), args.build.resolve()
    build.mkdir(parents=True, exist_ok=True)
    config = build / ".config"
    os.environ["srctree"] = str(source)
    os.environ["KCONFIG_CONFIG"] = str(config)
    os.environ["ARTOS_BUILD_TYPE"] = args.build_type
    kconf = kconfiglib.Kconfig(str(source / "Kconfig"), warn_to_stderr=False)
    kconf.warn_assign_undef = True
    kconf.load_config(str(config if config.exists() else args.defconfig.resolve()))
    # Force evaluation before checking warnings (e.g. invalid numeric ranges).
    for symbol in kconf.unique_defined_syms:
        _ = symbol.str_value
    if kconf.warnings:
        sys.exit("Invalid Kconfig configuration:\n" + "\n".join(kconf.warnings))
    hardware = {name: kconf.syms[name].str_value for name in
                ("BOARD_NAME", "BOARD_PATH", "SOC_PATH", "SOC_NAME", "CPU_NAME", "MCU_VARIANT")}
    if not all(hardware.values()):
        sys.exit("No supported board/SoC/CPU selected")
    kconf.write_config(str(config))
    if args.menuconfig:
        from menuconfig import menuconfig
        menuconfig(kconf)
        # CMake regenerates on the next build using the saved .config.
        return
    if args.savedefconfig:
        path = build / "defconfig"
        kconf.write_min_config(str(path))
        print(f"Saved minimal configuration to {path}")
        return

    enabled = bool(kconf.syms["ARTOS"].tri_value)
    # Disabled subsystem settings have no Kconfig value. Provide safe inert
    # defaults so public type declarations remain usable by compile-only checks.
    tick = int(kconf.syms["ARTOS_TICK_HZ"].str_value) if enabled else 1000
    scheduler_min_cycles_remaining = (int(kconf.syms["ARTOS_SCHEDULER_MIN_CYCLES_REMAINING"].str_value)
                                      if enabled else 0)
    priorities = int(kconf.syms["ARTOS_PRIORITY_LEVELS"].str_value) if enabled else 16
    max_threads = int(kconf.syms["ARTOS_MAX_THREADS"].str_value) if enabled else 8
    thread_stack_hwm = enabled and bool(kconf.syms["ARTOS_THREAD_STACK_HWM"].tri_value)
    thread_stats = enabled and bool(kconf.syms["ARTOS_THREAD_STATS"].tri_value)
    runtime_history_window_ms = (int(kconf.syms["ARTOS_RUNTIME_HISTORY_WINDOW_MS"].str_value)
                                 if thread_stats else 1000)
    runtime_history_bucket_count = (int(kconf.syms["ARTOS_RUNTIME_HISTORY_BUCKET_COUNT"].str_value)
                                    if thread_stats else 10)
    main_thread_stack_size = (int(kconf.syms["ARTOS_MAIN_THREAD_STACK_SIZE"].str_value)
                              if enabled else 4096)
    main_thread_priority = (int(kconf.syms["ARTOS_MAIN_THREAD_PRIORITY"].str_value)
                            if enabled else 0)
    max_deferred_work_items = int(kconf.syms["ARTOS_MAX_DEFERRED_WORK_ITEMS"].str_value) if enabled else 8
    max_active_guards = int(kconf.syms["ARTOS_MAX_ACTIVE_GUARDS"].str_value) if enabled else 8
    priority_aging = enabled and bool(kconf.syms["ARTOS_SCHEDULER_PRIORITY_AGING"].tri_value)
    priority_aging_ticks = (str(int(kconf.syms["ARTOS_PRIORITY_AGING_TICKS"].str_value))
                            if priority_aging else "std::nullopt")
    scheduler_config = ("fixed_priority_round_robin_config { "
                        f".priority_aging_ticks = {priority_aging_ticks} }}")
    monitor_enabled = bool(kconf.syms["MONITOR"].tri_value)
    console_enabled = bool(kconf.syms["CONSOLE"].tri_value)
    rx_size = int(kconf.syms["CONSOLE_RX_BUFFER_SIZE"].str_value) if console_enabled else 0
    generated = build / "generated"
    generated.mkdir(exist_ok=True)
    kconf.write_autoconf(str(generated / "autoconf.h"))
    write_changed(generated / "build_config.h", f'''// Generated by scripts/configure.py. Edit .config through menuconfig.
#pragma once
#include <cstddef>
#include <cstdint>
#include <optional>
#include <autoconf.h>

namespace build_config {{
    namespace artos {{
        struct fixed_priority_round_robin_config {{
            std::optional<std::uint32_t> priority_aging_ticks;
        }};

        inline constexpr bool enabled = {str(enabled).lower()};
        inline constexpr std::uint32_t tick_hz = {tick};
        inline constexpr std::uint32_t scheduler_min_cycles_remaining = {scheduler_min_cycles_remaining};
        inline constexpr std::uint32_t priority_levels = {priorities};
        inline constexpr std::size_t max_threads = {max_threads};
        inline constexpr bool thread_stack_hwm = {str(thread_stack_hwm).lower()};
        inline constexpr bool thread_stats = {str(thread_stats).lower()};
        inline constexpr std::uint32_t runtime_history_window_ms = {runtime_history_window_ms};
        inline constexpr std::size_t runtime_history_bucket_count = {runtime_history_bucket_count};
        static_assert(runtime_history_window_ms > 0);
        static_assert(runtime_history_bucket_count > 0);
        static_assert(runtime_history_window_ms % runtime_history_bucket_count == 0,
                      "runtime history window must divide evenly by bucket count");
        inline constexpr std::uint32_t runtime_history_bucket_ms
            = runtime_history_window_ms / runtime_history_bucket_count;
        inline constexpr std::size_t main_thread_stack_size = {main_thread_stack_size};
        inline constexpr std::uint8_t main_thread_priority = {main_thread_priority};
        inline constexpr std::size_t max_deferred_work_items = {max_deferred_work_items};
        inline constexpr std::size_t max_active_guards = {max_active_guards};
        inline constexpr auto scheduler = {scheduler_config};
        static_assert(tick_hz > 0);
        static_assert(priority_levels > 0 && priority_levels <= 256);
        static_assert(max_threads >= 2 && max_threads <= 64);
        static_assert(main_thread_stack_size >= 1024 && main_thread_stack_size <= 65536);
        static_assert(main_thread_stack_size % 8 == 0);
        static_assert(main_thread_priority < priority_levels);
        static_assert(max_deferred_work_items >= 1 && max_deferred_work_items <= 64);
        static_assert(max_active_guards >= 1 && max_active_guards <= 64);
    }}
    namespace monitor {{
        inline constexpr bool enabled = {str(monitor_enabled).lower()};
    }}
    namespace console {{
        inline constexpr bool enabled = {str(console_enabled).lower()};
        inline constexpr std::size_t rx_buffer_size = {rx_size};
        static_assert(!enabled || (rx_buffer_size > 1 && rx_buffer_size <= UINT32_MAX));
    }}
}}
''')
    write_changed(generated / "config.cmake", f'''# Generated by scripts/configure.py.
set(CONFIG_BOARD "{hardware['BOARD_NAME']}")
set(CONFIG_BSP "{hardware['BOARD_PATH']}")
set(CONFIG_SOC_PATH "{hardware['SOC_PATH']}")
set(CONFIG_SOC "{hardware['SOC_NAME']}")
set(CONFIG_CPU "{hardware['CPU_NAME']}")
set(CONFIG_MCU_VARIANT "{hardware['MCU_VARIANT']}")
set(CONFIG_ARTOS {"ON" if enabled else "OFF"})
set(CONFIG_CONSOLE {"ON" if console_enabled else "OFF"})
set(CONFIG_MONITOR {"ON" if monitor_enabled else "OFF"})
''')


if __name__ == "__main__":
    main()
